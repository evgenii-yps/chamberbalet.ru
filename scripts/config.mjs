/**
 * Заголовки ответа, байт на запрос. ОЦЕНКА, а не измерение — отсюда и имя.
 *
 * Статический сторож видит только тела файлов, Lighthouse считает то, что
 * прошло по проводу вместе с заголовками. Без поправки статика систематически
 * мягче: сборка проходила бы её и не проходила Lighthouse.
 *
 * Снято серией: десять прогонов Lighthouse, по каждому запросу transferSize
 * минус ровно то тело, которое отдал сервер. Прогоны вышли побайтно
 * одинаковыми — 304 818 Б и двадцать запросов во всех десяти, — так что
 * разброс идёт не между прогонами, а между запросами, и он двугорбый:
 *
 *   сжатые   247…262, медиана 253 (100 выборок)
 *   несжатые 203…205, медиана 204 (90 выборок)
 *
 * Горбы объясняются целиком длиной строк: у сжатых ответов есть
 * Content-Encoding и Vary, вместе примерно 49 Б. Остаток внутри горба —
 * длина Content-Type: `text/html; charset=utf-8` на девять знаков длиннее
 * `text/javascript`, и ровно на девять байт тяжелее его заголовок.
 * Поэтому величина не одна, а две: одна ошибалась бы на полсотни байт на
 * каждом шрифте и каждом кадре.
 *
 * Почему это всё-таки оценка, а не константа:
 *
 *   снято на локальном сервере qa, а не на бою. Apache у рег.ру шлёт ещё
 *     Date, Server, ETag, Last-Modified, Accept-Ranges — значит настоящие
 *     заголовки тяжелее, и эта величина скорее пол, чем потолок;
 *   меняется от набора заголовков, а не от кода страницы: добавят Vary или
 *     CSP — и она уедет, хотя в dist не изменится ни байта;
 *   двадцатый запрос Chrome — повторный /favicon.svg с transferSize 0,
 *     он дедуплицирован и в счёт не идёт: оплачиваемых запросов 19.
 *
 * Перемерять — scripts/qa/lighthouse.mjs плюс тот же вычет по каждому
 * запросу; расхождение статики и Lighthouse печатается обоими сторожами.
 */
