"""Сверка обязательных фактов в готовом PDF.
Запуск: python3 check.py путь/к/Гастрольное_предложение.pdf
Нужен pdftotext (poppler-utils)."""
import re, subprocess, sys
pdf = sys.argv[1] if len(sys.argv) > 1 else "../Гастрольное_предложение.pdf"
raw = subprocess.run(["pdftotext", pdf, "-"], capture_output=True, text=True).stdout
t = raw.replace("\u00a0", " ").replace("\u202f", " ").replace("\u2009", " ")
t = re.sub(r"(?<=\d) (?=\d{3}\b)", "", t)          # 4 420 -> 4420
t = re.sub(r"\s+", " ", t).replace("—", "-").replace("–", "-")
flat = re.sub(r"\s+", "", t.lower())   # разрядка букв ломает извлечение — сравниваем без пробелов
must = ["4420","2720","3420","2320","2620","3020","5420","3295","4120","2745","2945","3345",
        "1000","575","700","425","325","$900","$25","50%","20%","30%",
        "северо-западный камерный балет","олеся гапиенко","+7 905 232-78-90","lesya84@yandex.ru",
        "петипа","вайнонена","без наценки","от 100 мест",
        "спящая красавица","чиполлино","волшебный бал","принцесса на горошине","amore","венский бал",
        "бах. совершенство в движении","последнее танго","шопениана","па-де-катр","пахита","времена года",
        "sinatra suite","чайковский. вечер великих балетов","опера и балет","дягилев","майя плисецкая","анна павлова",
        "живые декорации","интерактивная проекция","рижская весна","комлевой"]
forbid = ["вологд","снегурочк","несостоявш","театр не камерного","00 трупп","casa"]
ok = True
for s in must:
    hit = re.sub(r"\s+", "", s) in flat
    ok &= hit
    print(("✓ " if hit else "✗ НЕТ  ") + s)
for s in forbid:
    hit = re.sub(r"\s+", "", s) in flat
    ok &= not hit
    print(("✗ ЗАПРЕЩЕНО  " if hit else "✓ нет  ") + s)
print("\nИТОГ:", "ВСЁ НА МЕСТЕ" if ok else "ЕСТЬ РАСХОЖДЕНИЯ")
sys.exit(0 if ok else 1)
